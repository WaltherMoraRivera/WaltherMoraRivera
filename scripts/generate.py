def code(x, y, parts, size=14, weight="700"):
    """One line of syntax-colored monospace text: parts is a list of (text, css class)."""
    spans = "".join(f'<tspan class="{cls}">{esc(text)}</tspan>' for text, cls in parts)
    return f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}" class="m" xml:space="preserve">{spans}</text>'


def bevel(x, y, w, h, raised=True):
    """Classic 3D edge: light top-left and dark bottom-right (raised), or the reverse (sunken)."""
    r = lambda rx, ry, rw, rh, c: f'<rect x="{rx}" y="{ry}" width="{rw}" height="{rh}" class="{c}"/>'
    if raised:
        return (r(x, y, w, 1, "hi") + r(x, y, 1, h, "hi") + r(x, y + h - 1, w, 1, "dk") + r(x + w - 1, y, 1, h, "dk")
                + r(x + 1, y + h - 2, w - 2, 1, "sh") + r(x + w - 2, y + 1, 1, h - 2, "sh"))
    return (r(x, y, w, 1, "sh") + r(x, y, 1, h, "sh") + r(x + 1, y + 1, w - 2, 1, "dk") + r(x + 1, y + 1, 1, h - 2, "dk")
            + r(x, y + h - 1, w, 1, "hi") + r(x + w - 1, y, 1, h, "hi"))


