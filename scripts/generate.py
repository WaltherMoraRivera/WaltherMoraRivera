def layout_chips(labels, x0, max_x, size=12, pad=9, gap=6, quoted=False):
    """quoted: the editor theme shows stack items as "strings", two characters wider."""
    x, row, out = x0, 0, []
    for label in labels:
        w = text_width(label, size) * 0.95 + 2 * pad + (14 if quoted else 0)
        if x + w > max_x and x > x0:
            row += 1
            x = x0
        out.append((label, x, row, w))
        x += w + gap
    return out, row + 1


