def fit(s, size, width, mono=False):
    """Cut s with an ellipsis so it fits width."""
    if text_width(s, size, mono=mono) <= width:
        return s
    while s and text_width(s + "…", size, mono=mono) > width:
        s = s[:-1]
    return s + "…"


